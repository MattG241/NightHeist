def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_path = os.path.join(root, "src", "core", "nh_font5x7.c")
    lines = [
        "/* Generated by tools/gen_font.py - do not edit by hand. */",
        "/* 5x7 font, original work for Night Heist, released under CC0. */",
        '#include "nh_font.h"',
        "",
        "/* One byte per row, bit 4 = leftmost column. Codes 32..127. */",
        "const uint8_t nh_font5x7[NH_FONT_GLYPHS][7] = {",
    ]
    for code in range(32, 128):
        ch = chr(code)
        rows = GLYPHS.get(ch)
        if rows is None or len(rows) != 7 or any(len(r) != 5 for r in rows):
            sys.exit("glyph %r is missing or malformed" % ch)
        vals = []
        for r in rows:
            v = 0
            for i, p in enumerate(r):
                if p == "#":
                    v |= 1 << (4 - i)
            vals.append("0x%02x" % v)
        label = "DEL" if code == 127 else ("'\\\\'" if ch == "\\" else repr(ch))
        lines.append("    { %s }, /* %s */" % (", ".join(vals), label))
    lines.append("};")
    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out_path)


if __name__ == "__main__":
    main()
